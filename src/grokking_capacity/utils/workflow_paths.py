def script_source(name, root=ROOT):
    stem = Path(name).stem
    return Path(root) / SOURCES[stem]


def frozen_source(campaign, name):
    """Locate an immutable worker in either historical or packaged snapshots."""
    source = Path(campaign) / "source"
    candidates = [source / "scripts" / name, source / SOURCES[Path(name).stem]]
    for path in candidates:
        if path.is_file():
            return path
    raise FileNotFoundError(f"No frozen {name} source in {source}")
